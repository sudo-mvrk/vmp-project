-- Slice 2 (Q-E): an organization gets its own generated id instead of sharing the user's id,
-- and accounts are linked to organizations through organization_member.

-- Existing organizations keep their id; until now it was the owner's user id, which the backfill uses.
ALTER TABLE organizations DROP CONSTRAINT fk_organizations_user;
ALTER TABLE organizations ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('organizations', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM organizations;

CREATE TABLE organization_member (
    organization_id BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    role            VARCHAR(20) NOT NULL,
    CONSTRAINT pk_organization_member PRIMARY KEY (organization_id, user_id),
    CONSTRAINT fk_organization_member_organization FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_organization_member_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT ck_organization_member_role CHECK (role IN ('OWNER')),
    -- Q2d: an account belongs to at most one organization in the MVP.
    CONSTRAINT uq_organization_member_user UNIQUE (user_id)
);

-- Exactly one owner per organization: at most one by this index, at least one by the service.
CREATE UNIQUE INDEX uq_organization_member_owner ON organization_member (organization_id) WHERE role = 'OWNER';

INSERT INTO organization_member (organization_id, user_id, role)
SELECT id, id, 'OWNER' FROM organizations;
