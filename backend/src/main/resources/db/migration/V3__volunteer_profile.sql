-- Slice 3: volunteer profile with skills, certifications, weekly availability and capacity.

-- Q3h, Q3e, Q3g. Radius values outside the new range cannot be kept; the dev database holds no real data.
ALTER TABLE volunteers ADD COLUMN bio TEXT;
ALTER TABLE volunteers ADD COLUMN max_active_assignments INTEGER NOT NULL DEFAULT 1;
ALTER TABLE volunteers ADD CONSTRAINT ck_volunteers_max_active_assignments CHECK (max_active_assignments BETWEEN 0 AND 10);
UPDATE volunteers SET radius = NULL WHERE radius NOT BETWEEN 1 AND 500;
ALTER TABLE volunteers ADD CONSTRAINT ck_volunteers_radius CHECK (radius BETWEEN 1 AND 500);

-- Certification dictionary (Q14). Self-declared, no verification.
CREATE TABLE certifications (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uq_certifications_name UNIQUE (name)
);

-- Skills a volunteer has; binary, no levels (Q7).
CREATE TABLE volunteer_skill (
    volunteer_id BIGINT NOT NULL,
    skill_id     BIGINT NOT NULL,
    CONSTRAINT pk_volunteer_skill PRIMARY KEY (volunteer_id, skill_id),
    CONSTRAINT fk_volunteer_skill_volunteer FOREIGN KEY (volunteer_id) REFERENCES volunteers (id) ON DELETE CASCADE,
    CONSTRAINT fk_volunteer_skill_skill FOREIGN KEY (skill_id) REFERENCES skills (id)
);

-- valid_until is inclusive; NULL means the certification does not expire (Q14a).
CREATE TABLE volunteer_certification (
    volunteer_id     BIGINT NOT NULL,
    certification_id BIGINT NOT NULL,
    valid_until      DATE,
    CONSTRAINT pk_volunteer_certification PRIMARY KEY (volunteer_id, certification_id),
    CONSTRAINT fk_volunteer_certification_volunteer FOREIGN KEY (volunteer_id) REFERENCES volunteers (id) ON DELETE CASCADE,
    CONSTRAINT fk_volunteer_certification_certification FOREIGN KEY (certification_id) REFERENCES certifications (id)
);

-- Weekly slots (Q13). The service rejects overlapping slots of one day (Q3d).
CREATE TABLE volunteer_availability (
    volunteer_id BIGINT      NOT NULL,
    day_of_week  VARCHAR(9)  NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    CONSTRAINT pk_volunteer_availability PRIMARY KEY (volunteer_id, day_of_week, start_time),
    CONSTRAINT fk_volunteer_availability_volunteer FOREIGN KEY (volunteer_id) REFERENCES volunteers (id) ON DELETE CASCADE,
    CONSTRAINT ck_volunteer_availability_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_volunteer_availability_range CHECK (start_time < end_time)
);

