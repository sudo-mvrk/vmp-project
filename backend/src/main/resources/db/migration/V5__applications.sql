-- Slice 5: applications of volunteers to activities.

CREATE TABLE applications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id BIGINT       NOT NULL,
    activity_id  BIGINT       NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    -- Slice 5b adds INVITATION.
    origin       VARCHAR(20)  NOT NULL,
    applied_at   TIMESTAMP(6) NOT NULL,
    decided_at   TIMESTAMP(6),
    -- Optimistic lock: an accept and a withdraw of the same application cannot both win.
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_applications_volunteer FOREIGN KEY (volunteer_id) REFERENCES volunteers (id) ON DELETE CASCADE,
    CONSTRAINT fk_applications_activity FOREIGN KEY (activity_id) REFERENCES activities (id) ON DELETE CASCADE,
    CONSTRAINT ck_applications_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_applications_origin CHECK (origin IN ('APPLICATION')),
    -- Q5b: one application per volunteer and activity, ever.
    CONSTRAINT uq_applications_volunteer_activity UNIQUE (volunteer_id, activity_id)
);

-- Free spots of an activity and the active assignments of a volunteer are counted by status.
CREATE INDEX ix_applications_activity_status ON applications (activity_id, status);
CREATE INDEX ix_applications_volunteer_status ON applications (volunteer_id, status);
