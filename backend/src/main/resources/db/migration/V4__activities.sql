-- Slice 4: activities of an organization, with required skills and certifications.

CREATE TABLE activities (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT                NOT NULL,
    title             VARCHAR(150)          NOT NULL,
    short_description VARCHAR(500),
    full_description  TEXT,
    -- Q8: priority is required, MEDIUM by default.
    priority          VARCHAR(10)           NOT NULL DEFAULT 'MEDIUM',
    status            VARCHAR(20)           NOT NULL,
    -- Q4b: every activity has a location.
    location          geometry(Point, 4326) NOT NULL,
    city              VARCHAR(255),
    full_address      VARCHAR(255),
    -- Q4a: local times in the configured zone.
    starts_at         TIMESTAMP(0)          NOT NULL,
    ends_at           TIMESTAMP(0)          NOT NULL,
    spots_needed      INTEGER               NOT NULL,
    -- Q12: optional weight override, all three or none.
    weight_alpha      DOUBLE PRECISION,
    weight_beta       DOUBLE PRECISION,
    weight_gamma      DOUBLE PRECISION,
    created_at        TIMESTAMP(6)          NOT NULL,
    updated_at        TIMESTAMP(6)          NOT NULL,
    CONSTRAINT fk_activities_organization FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT ck_activities_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_activities_status CHECK (status IN ('DRAFT', 'OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_activities_window CHECK (starts_at < ends_at),
    CONSTRAINT ck_activities_spots_needed CHECK (spots_needed BETWEEN 1 AND 1000),
    CONSTRAINT ck_activities_weights CHECK (num_nulls(weight_alpha, weight_beta, weight_gamma) IN (0, 3))
);

CREATE INDEX ix_activities_organization ON activities (organization_id);
-- Public listing: open activities by start time.
CREATE INDEX ix_activities_status_starts_at ON activities (status, starts_at);

-- Binary requirements, no weights (Q7).
CREATE TABLE activity_required_skill (
    activity_id BIGINT NOT NULL,
    skill_id    BIGINT NOT NULL,
    CONSTRAINT pk_activity_required_skill PRIMARY KEY (activity_id, skill_id),
    CONSTRAINT fk_activity_required_skill_activity FOREIGN KEY (activity_id) REFERENCES activities (id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_required_skill_skill FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE activity_required_certification (
    activity_id      BIGINT NOT NULL,
    certification_id BIGINT NOT NULL,
    CONSTRAINT pk_activity_required_certification PRIMARY KEY (activity_id, certification_id),
    CONSTRAINT fk_activity_required_certification_activity FOREIGN KEY (activity_id) REFERENCES activities (id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_required_certification_certification FOREIGN KEY (certification_id) REFERENCES certifications (id)
);
