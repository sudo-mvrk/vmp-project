package com.volunnear.evaluation;

import com.volunnear.distribution.scoring.ScoringWeights;
import com.volunnear.evaluation.ListQuality.Ordering;

import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Writes RESULTS.md and runs.csv (Q50): plain Markdown tables with numbered captions and a "how to read" line, and
 * facts without conclusions, so the file converts with pandoc and can be handed to Claude to draft the chapter.
 */
final class ReportWriter {
    private static final List<Method> METHODS = List.of(Method.RANDOM, Method.NEAREST, Method.SMART_A, Method.SMART_B);
    private static final List<Method> SMART = List.of(Method.SMART_A, Method.SMART_B);
    private static final List<Method> BASELINES = List.of(Method.RANDOM, Method.NEAREST);
    private static final List<Metrics.Kind> SENSITIVITY_METRICS = List.of(
            Metrics.Kind.M1, Metrics.Kind.M4, Metrics.Kind.M6, Metrics.Kind.M8, Metrics.Kind.M10);

    /** One data set: its name and sizes as configured for the seed, and the evaluation on it. */
    record Scale(String name, int organizations, int volunteers, int activities, Evaluation.Result result) {
    }

    /** One weight set of the sensitivity analysis. */
    record WeightSet(String name, Evaluation.Result result) {
    }

    /** What the Setup section states about the run. */
    record Setup(String generatedAt, String commit, long seedRandom, String dataNow, int runs, ScoringWeights weights,
                 double halfDistanceKm) {
    }

    /** Below this a value prints as 0.000. */
    private static final double ROUNDS_TO_ZERO = 0.0005;

    private final StringBuilder out = new StringBuilder();
    private int table;

    private ReportWriter() {
    }

    static String markdown(Setup setup, List<Scale> scales, String sensitivityScale, List<WeightSet> sensitivity) {
        ReportWriter writer = new ReportWriter();
        writer.write(setup, scales, sensitivityScale, sensitivity);
        return writer.out.toString();
    }

    static String csv(List<Scale> scales, String sensitivityScale, List<WeightSet> sensitivity) {
        StringBuilder csv = new StringBuilder("scale,weights,run,method");
        for (Metrics.Kind kind : Metrics.Kind.values()) {
            csv.append(',').append(kind.name());
        }
        csv.append('\n');
        for (Scale scale : scales) {
            appendRuns(csv, scale.name(), "default", scale.result());
        }
        for (WeightSet set : sensitivity) {
            appendRuns(csv, sensitivityScale, set.name(), set.result());
        }
        return csv.toString();
    }

    private static void appendRuns(StringBuilder csv, String scale, String weights, Evaluation.Result result) {
        for (Method method : METHODS) {
            List<Metrics> runs = result.runs().get(method);
            for (int r = 0; r < runs.size(); r++) {
                csv.append(scale).append(',').append(weights).append(',').append(r + 1).append(',').append(method.label);
                for (Metrics.Kind kind : Metrics.Kind.values()) {
                    double value = runs.get(r).value(kind);
                    csv.append(',').append(Double.isNaN(value) ? "" : String.format(Locale.ROOT, "%.6f", value));
                }
                csv.append('\n');
            }
        }
    }

    private void write(Setup setup, List<Scale> scales, String sensitivityScale, List<WeightSet> sensitivity) {
        line("# Evaluation results");
        line("");
        line("Generated by `EvaluationRunnerTest` (`cd backend && ./mvnw test -Pevaluation`) on " + setup.generatedAt()
                + ". Do not edit: the next run overwrites this file. Methods, metrics and threats to validity are defined in `METHOD.md`; raw numbers per run are in `runs.csv`.");
        line("");
        line("Methods: **random** = the old solution (unsorted list, the volunteer takes any fitting activity); **nearest** = a volunteer of the old solution who picks the closest activity; **smart-A** = the volunteer takes the top recommendation; **smart-B** = each activity takes its best-scored volunteer (argmax of `FUNCTION.md` section 4). All methods choose only among feasible pairs.");
        line("");

        line("## Setup");
        line("");
        line("| Parameter | Value |");
        line("|---|---|");
        line("| Code version (git commit) | `" + setup.commit() + "` |");
        line("| Seed of the data generator | " + setup.seedRandom() + " |");
        line("| Data generated as of | " + setup.dataNow() + " (fixed, so every run sees the same data) |");
        line("| Runs per method | " + setup.runs() + " (volunteer order seeded by the run number) |");
        ScoringWeights w = setup.weights();
        line("| Weights alpha / beta / gamma | " + fmt(w.alpha()) + " / " + fmt(w.beta()) + " / " + fmt(w.gamma()) + " |");
        line("| Half-distance of u_geo | " + fmt(setup.halfDistanceKm()) + " km |");
        line("| List sizes k | 5, 10 |");
        line("");

        caption("Data sets");
        line("| Scale | Organisations | Volunteers | Open upcoming activities | Spots to fill | Volunteers with a feasible activity | Mean feasible activities per volunteer |");
        line("|---|---|---|---|---|---|---|");
        for (Scale scale : scales) {
            Scenario scenario = scale.result().scenario();
            List<Integer> feasible = scenario.volunteers().stream()
                    .map(volunteer -> Simulation.options(volunteer, scenario.activities()).size()).toList();
            long withFeasible = feasible.stream().filter(count -> count > 0).count();
            line("| " + scale.name() + " | " + scale.organizations() + " | " + scenario.volunteers().size() + " | "
                    + scenario.activities().size() + " | " + scenario.spotsToFill() + " | " + withFeasible + " | "
                    + fmt(feasible.stream().mapToInt(Integer::intValue).average().orElse(Double.NaN)) + " |");
        }
        howToRead("Spots to fill are the free spots of the open upcoming activities before the run (the seed's demo applications already use some). "
                + "\"Feasible\" means available, certified, with capacity, open with a free spot, and within the volunteer's radius.");

        for (Scale scale : scales) {
            writeScale(scale);
        }
        writeSensitivity(sensitivityScale, sensitivity);
    }

    private void writeScale(Scale scale) {
        Evaluation.Result result = scale.result();
        int runs = result.runs().get(Method.RANDOM).size();
        line("## Scale " + scale.name() + " (" + scale.volunteers() + " volunteers, " + scale.activities() + " activities)");
        line("");

        caption("Distribution quality, scale " + scale.name() + " (mean ± standard deviation over " + runs + " runs)");
        line("| Metric | Better | random | nearest | smart-A | smart-B |");
        line("|---|---|---|---|---|---|");
        for (Metrics.Kind kind : Metrics.Kind.values()) {
            StringBuilder row = new StringBuilder("| " + kind.label() + " | " + (kind.higherIsBetter ? "higher" : "lower"));
            for (Method method : METHODS) {
                Summary summary = result.summary(method, kind);
                row.append(" | ").append(fmt(summary.mean())).append(" ± ").append(fmt(summary.std()));
            }
            line(row + " |");
        }
        howToRead("Each cell is the mean of the metric over the runs and its standard deviation. Shares are between 0 and 1. "
                + "smart-B does not depend on the volunteer order, so its deviation is 0.");

        caption("95% confidence intervals of the means, scale " + scale.name());
        line("| Metric | random | nearest | smart-A | smart-B |");
        line("|---|---|---|---|---|");
        for (Metrics.Kind kind : Metrics.Kind.values()) {
            StringBuilder row = new StringBuilder("| " + kind.label());
            for (Method method : METHODS) {
                Summary summary = result.summary(method, kind);
                row.append(" | ").append(fmt(summary.mean() - summary.ci95())).append(" … ")
                        .append(fmt(summary.mean() + summary.ci95()));
            }
            line(row + " |");
        }
        howToRead("Interval mean ± 1.96 · s / √n. Intervals of two methods that do not overlap indicate a difference that is not explained by the variation between runs.");

        caption("Paired comparison, scale " + scale.name() + ": runs (of " + runs + ") in which smart is strictly better");
        line("| Metric | smart-A vs random | smart-A vs nearest | smart-B vs random | smart-B vs nearest |");
        line("|---|---|---|---|---|");
        for (Metrics.Kind kind : Metrics.Kind.values()) {
            StringBuilder row = new StringBuilder("| " + kind.label());
            for (Method smart : SMART) {
                for (Method baseline : BASELINES) {
                    row.append(" | ").append(result.wins(smart, baseline, kind));
                }
            }
            line(row + " |");
        }
        howToRead("All methods of one run use the same volunteer order. A tie counts as not better, so the two directions need not add up to the number of runs.");

        if (!result.lists().isEmpty()) {
            caption("List quality, scale " + scale.name() + ": the first k activities a volunteer sees (initial state)");
            line("| k | List | Skill coverage | Mean distance, km | Share of HIGH and URGENT |");
            line("|---|---|---|---|---|");
            for (Map.Entry<Integer, Map<Ordering, List<ListQuality.Values>>> entry : result.lists().entrySet()) {
                for (Ordering ordering : Ordering.values()) {
                    List<ListQuality.Values> values = entry.getValue().get(ordering);
                    line("| " + entry.getKey() + " | " + ordering.label
                            + " | " + cell(Summary.of(values, ListQuality.Values::skillCoverage))
                            + " | " + cell(Summary.of(values, ListQuality.Values::meanDistanceKm))
                            + " | " + cell(Summary.of(values, ListQuality.Values::highUrgentShare)) + " |");
                }
            }
            howToRead("Averages over volunteers with at least one feasible activity. Only the unsorted list changes between runs (mean ± standard deviation over runs); "
                    + "the other two are the same in every run. A volunteer with fewer than k feasible activities gets a shorter list.");
        }

        line("### Facts, scale " + scale.name());
        line("");
        for (Metrics.Kind kind : Metrics.Kind.values()) {
            line("- " + fact(result, kind, runs));
        }
        line("");
    }

    private String fact(Evaluation.Result result, Metrics.Kind kind, int runs) {
        double smartA = result.summary(Method.SMART_A, kind).mean();
        double random = result.summary(Method.RANDOM, kind).mean();
        double nearest = result.summary(Method.NEAREST, kind).mean();
        return kind.label() + " (" + (kind.higherIsBetter ? "higher" : "lower") + " is better): "
                + "smart-A " + fmt(smartA) + ", smart-B " + fmt(result.summary(Method.SMART_B, kind).mean())
                + ", random " + fmt(random) + ", nearest " + fmt(nearest) + ". "
                + "smart-A minus random " + difference(smartA, random) + ", smart-A minus nearest " + difference(smartA, nearest) + ". "
                + "smart-A is better than random in " + result.wins(Method.SMART_A, Method.RANDOM, kind) + "/" + runs
                + " runs and than nearest in " + result.wins(Method.SMART_A, Method.NEAREST, kind) + "/" + runs + ".";
    }

    private void writeSensitivity(String scaleName, List<WeightSet> sensitivity) {
        line("## Sensitivity to the weights (scale " + scaleName + ")");
        line("");
        caption("Means of selected metrics for different weights alpha / beta / gamma, scale " + scaleName);
        StringBuilder header = new StringBuilder("| Weights | Method");
        StringBuilder rule = new StringBuilder("|---|---");
        for (Metrics.Kind kind : SENSITIVITY_METRICS) {
            header.append(" | ").append(kind.label());
            rule.append("|---");
        }
        line(header + " |");
        line(rule + "|");
        for (WeightSet set : sensitivity) {
            for (Method method : SMART) {
                sensitivityRow(set.name(), method, set.result());
            }
        }
        // the baselines never look at the weights; shown once, from the first set
        for (Method method : BASELINES) {
            sensitivityRow("any", method, sensitivity.get(0).result());
        }
        howToRead("Only smart-A and smart-B use the weights; random and nearest are the same for every weight set. "
                + "The two activities with their own weight override keep it in every set (smart-B only).");
    }

    private void sensitivityRow(String weights, Method method, Evaluation.Result result) {
        StringBuilder row = new StringBuilder("| " + weights + " | " + method.label);
        for (Metrics.Kind kind : SENSITIVITY_METRICS) {
            row.append(" | ").append(fmt(result.summary(method, kind).mean()));
        }
        line(row + " |");
    }

    private static String cell(Summary summary) {
        return summary.std() < ROUNDS_TO_ZERO ? fmt(summary.mean()) : fmt(summary.mean()) + " ± " + fmt(summary.std());
    }

    private static String difference(double a, double b) {
        if (Double.isNaN(a) || Double.isNaN(b)) {
            return "n/a";
        }
        String absolute = String.format(Locale.ROOT, "%+.3f", a - b);
        return b == 0 ? absolute : absolute + String.format(Locale.ROOT, " (%+.1f%%)", 100 * (a - b) / b);
    }

    private void caption(String text) {
        line("**Table " + (++table) + ". " + text + "**");
        line("");
    }

    private void howToRead(String text) {
        line("");
        line("*How to read:* " + text);
        line("");
    }

    private void line(String text) {
        out.append(text).append('\n');
    }

    private static String fmt(double value) {
        if (Double.isNaN(value)) {
            return "n/a";
        }
        // keeps "-0.000" out of the tables (a confidence interval of a share near 0 can dip below it)
        return String.format(Locale.ROOT, "%.3f", Math.abs(value) < ROUNDS_TO_ZERO ? 0.0 : value);
    }
}
